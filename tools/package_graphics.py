"""Build CHESS.DAT and its compiled resource index from generated graphics."""
from pathlib import Path
import hashlib
import json
import shutil
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = (
    'SPRITES', 'FONT', 'SPLTILE', 'SPLMAP', 'SPL1ART', 'SPL1MAP',
    'PALETTE', 'SETTILE', 'SETMAP', 'SET1ART', 'SET1MAP', 'SETPAL',
    'SQTILES', 'L0INFO', 'L0TILES', 'L0PLAIN', 'L1ART', 'ENGART', 'LETART', 'OPTMAP',
)
RUNTIME = ('CHESS.DAT',)
MAGIC = b'X16CHS01'
HEADER_SIZE = 16
RECORD = struct.Struct('<IH')  # 32-bit file offset, 16-bit byte count


def pack(source, destination):
    source, destination = Path(source), Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    assert (source / 'SPLPAL.DAT').read_bytes() == (source / 'PALETTE.DAT').read_bytes()
    offset = HEADER_SIZE + len(RESOURCES) * RECORD.size
    index, payload = bytearray(), bytearray()
    manifest = {}
    for name in RESOURCES:
        data = (source / (name + '.DAT')).read_bytes()
        assert 0 < len(data) <= 0xffff
        index.extend(RECORD.pack(offset, len(data)))
        manifest[name] = {'offset': offset, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
        payload.extend(data)
        offset += len(data)
    stamp = MAGIC + hashlib.sha256(index + payload).digest()[:8]
    # Guard byte means the last resource does not reach EOF on a persistent channel.
    packed = stamp + index + payload + b'\x00'
    (destination / 'CHESS.DAT').write_bytes(packed)
    for i, name in enumerate(RESOURCES):
        address, size = RECORD.unpack_from(packed, HEADER_SIZE + i * RECORD.size)
        assert packed[address:address + size] == (source / (name + '.DAT')).read_bytes()
    header = ['/* Generated by package_graphics.py; do not edit. */', '#ifndef ASSETS_H', '#define ASSETS_H']
    header.extend(f'#define ASSET_{name} {i}' for i, name in enumerate(RESOURCES))
    header.extend(['unsigned char __fastcall__ asset_prepare(unsigned char id);',
                   'unsigned char __fastcall__ asset_read(unsigned int destination);',
                   'extern unsigned char asset_stream;', '#endif', ''])
    (destination / 'assets.h').write_text('\n'.join(header))
    lines = ['; Generated by package_graphics.py; do not edit.', 'asset_expected:']
    lines.append('    .byte ' + ','.join(f'${byte:02x}' for byte in stamp))
    lines.append('asset_index:')
    for i, name in enumerate(RESOURCES):
        entry = index[i * RECORD.size:(i + 1) * RECORD.size]
        lines.append('    .byte ' + ','.join(f'${byte:02x}' for byte in entry) + f' ; {name}')
    (destination / 'assets.inc').write_text('\n'.join(lines) + '\n')
    shutil.copyfile(source / 'gfx.h', destination / 'gfx.h')
    (source / 'runtime-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Runtime graphics: CHESS.DAT ({len(packed)} bytes; {len(RESOURCES)} indexed resources)')


if __name__ == '__main__':
    pack(sys.argv[1], sys.argv[2])
