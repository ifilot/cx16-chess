"""Write src/strings.h: UI strings encoded in Windows-1251.

The layer-1 font stores glyphs in Windows-1251 order, so Cyrillic text can be
written here in UTF-8 and is emitted as escaped C string literals.
"""
import sys
from pathlib import Path

STRINGS = {
    'PLAYER1': 'ИГРОК 1',
    'PLAYER2': 'ИГРОК 2',
    'WHITE': 'БЕЛЫЕ',
    'BLACK': 'ЧЁРНЫЕ',
    'TO_MOVE': 'ХОД',
    'WHITE_GEN': 'БЕЛЫХ',      # "white's (move)"
    'BLACK_GEN': 'ЧЁРНЫХ',
    'CHECK': 'ШАХ',
    'WHITE_DAT': 'БЕЛЫМ',      # "(check) to white"
    'BLACK_DAT': 'ЧЁРНЫМ',
    'MATE': 'МАТ!',
    'STALEMATE': 'ПАТ',
    'DRAW': 'НИЧЬЯ',
    'TIME': 'ВРЕМЯ',
    'PROMOTE': 'ФИГУРА?',
    'WHITE_WINS': '1-0',
    'BLACK_WINS': '0-1',
    'DRAWN': '1/2',
    'PLACEHOLDER': '---',
    'HUMAN': 'ИГРОК',
    'COMPUTER': 'ЭВМ',          # Soviet term for a computer
    'THINKS': 'ДУМАЕТ',
    'REPETITION': 'ПОВТОР',
}


def c_literal(text):
    out = ''
    for byte in text.encode('cp1251'):
        out += chr(byte) if 32 <= byte < 127 and chr(byte) not in '"\\' else f'\\x{byte:02X}""'
    return '"' + out + '"'


def main(path):
    lines = ['/* Generated by assets/scripts/build_strings.py - do not edit. */',
             '#ifndef _STRINGS_H', '#define _STRINGS_H', '']
    for name, text in STRINGS.items():
        lines.append(f'#define STR_{name:<12} {c_literal(text):<40} /* {text} */')
    lines += ['', '#endif', '']
    Path(path).write_text('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'strings.h')
