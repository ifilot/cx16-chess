"""Write src/strings.h from the active English UI strings."""
import sys
from pathlib import Path

STRINGS = {
    'WHITE': 'WHITE',
    'BLACK': 'BLACK',
    'CHECK': 'CHECK',
    'WHITE_DAT': 'WHITE',      # "(check) to white"
    'BLACK_DAT': 'BLACK',
    'MATE': 'MATE',
    'STALEMATE': 'STALEMATE',
    'DRAW': 'DRAW',
    'TIME': 'TIME',
    'PROMOTE': 'PROMOTE',
    'WHITE_WINS': '1-0',
    'BLACK_WINS': '0-1',
    'DRAWN': '1/2',
    'REPETITION': 'REPETITION',
}


def c_literal(text):
    out = ''
    for byte in text.encode('cp1251'):
        out += chr(byte) if 32 <= byte < 127 and chr(byte) not in '"\\' else f'\\x{byte:02X}""'
    return '"' + out + '"'


def main(path):
    lines = ['/* Generated by assets/scripts/build_strings.py - do not edit. */',
             '#ifndef _STRINGS_H', '#define _STRINGS_H', '']
    for name, text in STRINGS.items():
        lines.append(f'#define STR_{name:<12} {c_literal(text):<40} /* {text} */')
    lines += ['', '#endif', '']
    Path(path).write_text('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'strings.h')
